// Creates web/.env.local with fresh random secrets for the local prototype (git-ignored).
// WEB_SESSION_SECRET signs session cookies; WEB_CNIC_PEPPER keys the CNIC uniqueness HMAC. Since
// Step 5h the website holds no wallet key (custody is in the signing service, ADR 0010), so no
// WEB_WALLET_KEY is created; an existing one is only read once by `npm run signer:import-web-wallets`.
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const file = fileURLToPath(new URL("../.env.local", import.meta.url));
if (existsSync(file)) {
  console.log("web/.env.local already exists; leaving it unchanged.");
} else {
  writeFileSync(
    file,
    [
      "# LOCAL DEV ONLY. Generated by scripts/setup-demo.mjs. Never commit.",
      `WEB_SESSION_SECRET=${randomBytes(32).toString("base64url")}`,
      `WEB_CNIC_PEPPER=${randomBytes(32).toString("base64url")}`,
      "",
    ].join("\n"),
  );
  console.log("Created web/.env.local with new secrets.");
}
