export function analystDict(lang: Lang): AnalystDict {
  return lang === "ur" ? ur : en;
}

/** A text by computed key (prefix + value), or the fallback. Avoids indexing with untrusted keys. */
export function aLabel(d: AnalystDict, key: string, fallback = key): string {
  const v = new Map<string, string>(Object.entries(d)).get(key);
  return v ?? fallback;
}

/** Fills {name} placeholders. Values are inserted literally (no further substitution). */
export function fillA(text: string, values: Record<string, string | number>): string {
  const m = new Map(Object.entries(values));
  return text.replace(/\{([a-z]+)\}/gi, (whole, k: string) => {
    const v = m.get(k);
    return v === undefined ? whole : String(v);
  });
}

export function analystSuggestions(lang: Lang, scope: "site" | "property" | "portfolio"): string[] {
  const d = analystDict(lang);
  const s = scope === "portfolio" ? d.sug_portfolio : scope === "property" ? d.sug_property : d.sug_site;
  return s.split("|");
}
