export function catalogDict(lang: Lang): CatalogDict {
  return lang === "ur" ? ur : en;
}

/** A label by prefix + key (statuses, occupancy, document types), falling back to the key. */
export function clabel(d: CatalogDict, prefix: "status_" | "occ_" | "f_" | "fi_" | "dt_" | "doc_" | "kind_" | "err_" | "sort_", key: string, fallback = key): string {
  return new Map(Object.entries(d)).get(`${prefix}${key}`) ?? fallback;
}

/** A PKT date-time "YYYY-MM-DD HH:MM" from an ISO time (Pakistan has no daylight saving). */
export function pktTime(iso: string): string {
  const d = new Date(new Date(iso).getTime() + 5 * 3_600_000);
  return d.toISOString().slice(0, 16).replace("T", " ");
}

export function pktDate(iso: string): string {
  return pktTime(iso).slice(0, 10);
}
