export const EXIT_DICTS = { en, ur } as const;

export function exitDict(lang: Lang): ExitDict {
  return lang === "ur" ? ur : en;
}

/** Looks up a dynamic key (a backend state or code) with a fallback, without indexing by user input. */
export function exitLabel(d: ExitDict, prefix: "st_" | "step_" | "now_" | "out_" | "pay_" | "rs_" | "w_" | "err_" | "werr_", key: string, fallback = key): string {
  const map = new Map(Object.entries(d));
  return map.get(`${prefix}${key}`) ?? fallback;
}
