/**
 * Creates or updates the website's login role (migration 0012, W-5): a member of pt_web only, with
 * no superuser, database, role or replication rights. Its password is generated here the first time
 * and appended to backend/.env.local (git-ignored) as WEB_PG_USER / WEB_PG_PASSWORD; it is never
 * printed. Idempotent: a re-run keeps the password and re-asserts the role's limits.
 *   npm run db:web-role               (needs migration 0012 in property_token)
 *   npm run db:web-role -- --test     (checks property_token_test instead; roles are cluster-wide)
 */
import { randomBytes } from "node:crypto";
import { appendFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { readEnvFile } from "@pt/config";
import pg from "pg";

const ENV_FILE = fileURLToPath(new URL("../../../.env.local", import.meta.url));

async function main(): Promise<void> {
  const local = readEnvFile(ENV_FILE);
  const user = local.WEB_PG_USER ?? "pt_web_app";
  if (!/^[a-z][a-z0-9_]{2,40}$/.test(user) || user === (local.PG_ADMIN_USER ?? "pt_admin")) throw new Error("WEB_PG_USER must be a separate lower-case role name");
  let password = local.WEB_PG_PASSWORD;
  if (!password) {
    password = randomBytes(24).toString("base64url");
    // eslint-disable-next-line security/detect-non-literal-fs-filename -- fixed path inside backend/
    await appendFile(ENV_FILE, `\n# website database role (generated by npm run db:web-role)\nWEB_PG_USER=${user}\nWEB_PG_PASSWORD=${password}\n`, { mode: 0o600 });
  }
  const client = new pg.Client({
    host: process.env.PG_HOST ?? local.PG_HOST ?? "127.0.0.1",
    port: Number(process.env.PG_PORT ?? local.PG_PORT ?? 5433),
    user: process.env.PG_ADMIN_USER ?? local.PG_ADMIN_USER ?? "pt_admin",
    password: process.env.PG_ADMIN_PASSWORD ?? local.PG_ADMIN_PASSWORD,
    database: process.argv.includes("--test") ? "property_token_test" : "property_token",
  });
  await client.connect();
  try {
    const group = await client.query("SELECT 1 FROM pg_roles WHERE rolname = 'pt_web'");
    if (group.rowCount !== 1) throw new Error("role pt_web does not exist: run npm run migrate first (migration 0012)");
    const exists = (await client.query("SELECT 1 FROM pg_roles WHERE rolname = $1", [user])).rowCount === 1;
    const id = client.escapeIdentifier(user);
    const limits = "LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS INHERIT CONNECTION LIMIT 60";
    // DDL cannot take parameters; the name is validated above and the password is escaped as a literal.
    await client.query(`${exists ? "ALTER" : "CREATE"} ROLE ${id} ${limits} PASSWORD ${client.escapeLiteral(password)}`);
    // Privileges come only through pt_web (inherited); the login role cannot SET ROLE or grant it on.
    await client.query(`GRANT pt_web TO ${id} WITH INHERIT TRUE, SET FALSE, ADMIN FALSE`);
    // Nothing else: drop any other membership a previous version might have granted.
    const other = await client.query<{ name: string }>(
      `SELECT g.rolname AS name FROM pg_auth_members m JOIN pg_roles g ON g.oid = m.roleid JOIN pg_roles u ON u.oid = m.member
       WHERE u.rolname = $1 AND g.rolname <> 'pt_web'`, [user]);
    for (const r of other.rows) await client.query(`REVOKE ${client.escapeIdentifier(r.name)} FROM ${id}`);
    process.stdout.write(`${exists ? "updated" : "created"} the website's database role ${user} (member of pt_web only)\n`);
  } finally {
    await client.end();
  }
}

main().catch((e: unknown) => {
  process.stderr.write(`${e instanceof Error ? e.message : String(e)}\n`);
  process.exitCode = 1;
});
