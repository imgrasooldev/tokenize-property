/**
 * npm run db:service-roles [-- --test]: creates or updates the backend services' login roles (see
 * service-roles.ts). Passwords are generated once and appended to the git-ignored backend/.env.local;
 * nothing secret is printed.
 */
import { randomBytes } from "node:crypto";
import { appendFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { envValue, readEnvFile, serviceRoles, type ServiceName } from "@pt/config";
import pg from "pg";
import { ensureServiceRoles } from "./service-roles.ts";

const ENV_FILE = fileURLToPath(new URL("../../../.env.local", import.meta.url));
const NAME = /^[a-z][a-z0-9_]{2,40}$/;

async function main(): Promise<void> {
  const local = readEnvFile(ENV_FILE);
  const admin = process.env.PG_ADMIN_USER ?? local.PG_ADMIN_USER ?? "pt_admin";
  const logins = new Map<ServiceName, { user: string; password: string }>();
  const lines: string[] = [];
  const taken = new Set<string>([admin, "postgres", local.WEB_PG_USER ?? "pt_web_app"]);
  for (const [service, { prefix, login }] of serviceRoles()) {
    const user = envValue(local, `${prefix}_PG_USER`) ?? login;
    if (!NAME.test(user) || taken.has(user)) throw new Error(`${prefix}_PG_USER must be a separate lower-case role name`);
    taken.add(user);
    let password = envValue(local, `${prefix}_PG_PASSWORD`);
    if (!password) {
      password = randomBytes(24).toString("base64url");
      lines.push(`${prefix}_PG_USER=${user}`, `${prefix}_PG_PASSWORD=${password}`);
    }
    logins.set(service, { user, password });
  }
  if (lines.length) {
    // eslint-disable-next-line security/detect-non-literal-fs-filename -- fixed path inside backend/
    await appendFile(ENV_FILE, `\n# backend service database roles (generated by npm run db:service-roles)\n${lines.join("\n")}\n`, { mode: 0o600 });
  }
  const target = {
    host: process.env.PG_HOST ?? local.PG_HOST ?? "127.0.0.1",
    port: Number(process.env.PG_PORT ?? local.PG_PORT ?? 5433),
    database: process.argv.includes("--test") ? "property_token_test" : "property_token",
  };
  const client = new pg.Client({ ...target, user: admin, password: process.env.PG_ADMIN_PASSWORD ?? local.PG_ADMIN_PASSWORD });
  await client.connect();
  try {
    const results = await ensureServiceRoles(client, logins);
    const created = results.filter((r) => r.created).length;
    process.stdout.write(`service database roles: ${String(created)} created, ${String(results.length - created)} updated (each a member of its pt_svc_* group only)\n`);
  } finally {
    await client.end();
  }
  // Every login must actually connect with the password the services will read (pg_hba, password),
  // so a deploy stops here instead of restarting services that cannot reach their database.
  for (const [service, login] of logins) {
    const c = new pg.Client({ ...target, ...login, connectionTimeoutMillis: 5_000 });
    try {
      await c.connect();
      await c.query("SELECT 1");
    } catch (e) {
      throw new Error(`the ${service} service's login cannot connect (${(e as { code?: string }).code ?? "error"})`, { cause: e });
    } finally {
      await c.end().catch(() => undefined);
    }
  }
  process.stdout.write("every service login connects\n");
}

main().catch((e: unknown) => {
  process.stderr.write(`${e instanceof Error ? e.message : String(e)}\n`);
  process.exitCode = 1;
});
