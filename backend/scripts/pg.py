"""Local PostgreSQL 18 for backend development (Step 5).

Usage (from the repository root):
    python backend/scripts/pg.py setup     # once: create the cluster, admin password, databases
    python backend/scripts/pg.py start     # start (127.0.0.1:5433 only)
    python backend/scripts/pg.py status
    python backend/scripts/pg.py stop
    python backend/scripts/pg.py psql      # open psql as the admin

Binaries come from the EnterpriseDB installer (Authenticode-verified, extract-only; see
backend/README.md). Data lives in backend/data/pg and the admin password in backend/.env.local,
both git-ignored. LOCAL DEVELOPMENT ONLY.
"""

import os
import secrets
import subprocess
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
BIN = BACKEND / "tools" / "pgsql" / "bin"
DATA = BACKEND / "data" / "pg"
LOG = BACKEND / "data" / "pg.log"
ENV_FILE = BACKEND / ".env.local"
HOST = "127.0.0.1"
PORT = 5433
ADMIN = "pt_admin"
DATABASES = ["property_token", "property_token_test"]


def exe(name: str) -> str:
    path = BIN / (name + (".exe" if os.name == "nt" else ""))
    if not path.exists():
        sys.exit(f"{path} not found. See backend/README.md for the verified PostgreSQL install.")
    return str(path)


def env_values() -> dict:
    out = {}
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text().splitlines():
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                out[k] = v
    return out


def admin_env() -> dict:
    env = dict(os.environ)
    env["PGPASSWORD"] = env_values()["PG_ADMIN_PASSWORD"]
    return env


def run(cmd, **kw):
    return subprocess.run(cmd, check=True, capture_output=True, text=True, **kw)


def cmd_setup(_args):
    if (DATA / "PG_VERSION").exists():
        print("Cluster already exists:", DATA.relative_to(BACKEND.parent))
        cmd_start([])
        ensure_databases()
        return
    DATA.parent.mkdir(parents=True, exist_ok=True)
    values = env_values()
    if "PG_ADMIN_PASSWORD" not in values:
        values["PG_ADMIN_PASSWORD"] = secrets.token_urlsafe(32)
        lines = ["# LOCAL DEV ONLY. Generated by backend/scripts/pg.py. Never commit."]
        lines += [f"{k}={v}" for k, v in values.items()]
        lines += [f"PG_HOST={HOST}", f"PG_PORT={PORT}", f"PG_ADMIN_USER={ADMIN}"]
        ENV_FILE.write_text("\n".join(lines) + "\n")
    pwfile = DATA.parent / ".pwfile"
    pwfile.write_text(values["PG_ADMIN_PASSWORD"])
    try:
        run([exe("initdb"), "-D", str(DATA), "-U", ADMIN, f"--pwfile={pwfile}",
             "--auth=scram-sha-256", "--encoding=UTF8", "--locale=C", "--data-checksums"])
    finally:
        pwfile.unlink(missing_ok=True)

    conf = DATA / "postgresql.conf"
    conf.write_text(conf.read_text() + f"""
# --- property-token local dev settings ---
listen_addresses = '{HOST}'
port = {PORT}
password_encryption = 'scram-sha-256'
log_connections = on
log_disconnections = on
log_statement = 'ddl'
log_min_duration_statement = 500
""")
    # Only password-authenticated TCP connections from this machine.
    (DATA / "pg_hba.conf").write_text(
        "# TYPE  DATABASE  USER  ADDRESS        METHOD\n"
        f"host    all       all   {HOST}/32   scram-sha-256\n"
    )
    cmd_start([])
    ensure_databases()
    print(f"Cluster ready at {HOST}:{PORT}; databases: {', '.join(DATABASES)}; admin password in backend/.env.local.")


def ensure_databases():
    existing = run([exe("psql"), "-h", HOST, "-p", str(PORT), "-U", ADMIN, "-d", "postgres", "-Atc",
                    "select datname from pg_database"], env=admin_env()).stdout.split()
    for db in DATABASES:
        if db not in existing:
            run([exe("createdb"), "-h", HOST, "-p", str(PORT), "-U", ADMIN, db], env=admin_env())
            print(f"created database {db}")


def is_running() -> bool:
    r = subprocess.run([exe("pg_isready"), "-h", HOST, "-p", str(PORT)], capture_output=True)
    return r.returncode == 0


def cmd_start(_args):
    if is_running():
        print("PostgreSQL already running")
        return
    # The server inherits pg_ctl's handles; never pipe them or this call would wait forever.
    subprocess.run([exe("pg_ctl"), "-D", str(DATA), "-l", str(LOG), "-w", "start"], check=True,
                   stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    print(f"PostgreSQL running on {HOST}:{PORT}")


def cmd_stop(_args):
    if not is_running():
        print("PostgreSQL not running")
        return
    run([exe("pg_ctl"), "-D", str(DATA), "-w", "stop", "-m", "fast"])
    print("PostgreSQL stopped")


def cmd_status(_args):
    if not is_running():
        print("PostgreSQL not running")
        return
    out = run([exe("psql"), "-h", HOST, "-p", str(PORT), "-U", ADMIN, "-d", "postgres", "-Atc",
               "select version(); select datname from pg_database where not datistemplate order by 1;"],
              env=admin_env()).stdout
    print(out.strip())


def cmd_psql(args):
    os.execve(exe("psql"), [exe("psql"), "-h", HOST, "-p", str(PORT), "-U", ADMIN, *(args or ["property_token"])],
              admin_env())


COMMANDS = {"setup": cmd_setup, "start": cmd_start, "stop": cmd_stop, "status": cmd_status, "psql": cmd_psql}

if __name__ == "__main__":
    if len(sys.argv) < 2 or sys.argv[1] not in COMMANDS:
        sys.exit(__doc__)
    COMMANDS[sys.argv[1]](sys.argv[2:])
