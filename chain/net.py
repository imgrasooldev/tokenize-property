"""Local 4-validator Hyperledger Besu QBFT network (Step 4).

A small copy of the production topology: four validators, 2-second blocks, immediate finality,
a node allow-list, RPC bound to localhost only, and zero gas price.

Usage (from the repository root):
    python chain/net.py setup            # once: dev accounts, validator keys, genesis, node configs
    python chain/net.py start            # start all four validators
    python chain/net.py status           # block height, peers, validators per node
    python chain/net.py stop [node4]     # stop all nodes, or one
    python chain/net.py start node4      # restart one node
    python chain/net.py reset            # stop and delete chain data (keeps keys and accounts)

Everything secret or generated lives in chain/network/generated/ and chain/network/dev-accounts.env,
both git-ignored. These are LOCAL DEVELOPMENT keys only; production validators are run by separate
organisations with their own key management.
"""

import json
import os
import shutil
import signal
import subprocess
import sys
import time
import urllib.request
from pathlib import Path

CHAIN = Path(__file__).resolve().parent
NETWORK = CHAIN / "network"
GENERATED = NETWORK / "generated"
DATA = CHAIN / "data"
TOOLS = CHAIN / "tools"
ACCOUNTS_FILE = NETWORK / "dev-accounts.env"

BESU_VERSION = "26.9.0"
CHAIN_ID = 586_586  # must equal DeployLib.LOCAL_DEV_CHAIN_ID; reserved for this local network only
NODES = 4
P2P_BASE = 30303
RPC_BASE = 8545
HOST = "127.0.0.1"
RPC_APIS = "ETH,NET,WEB3,QBFT,TXPOOL"  # no ADMIN, DEBUG or PERSONAL

# Roles used by the deploy script and the end-to-end flow. Safes are plain keys locally; in
# production they are Safe multisigs on hardware wallets.
ROLES = [
    "DEPLOYER",
    "ADMIN_SAFE",
    "TRUSTEE_SAFE",
    "ISSUANCE_SAFE",
    "OPS_SAFE",
    "PAUSER",
    "REGISTRAR",
    "IDENTITY_OPERATOR",
    "CLAIM_SIGNER",
    "ALICE",
    "BOB",
    "ALICE_NEW_WALLET",
]


# ------------------------------------------------------------------ helpers


def besu_bin() -> Path:
    exe = TOOLS / f"besu-{BESU_VERSION}" / "bin" / ("besu.bat" if os.name == "nt" else "besu")
    if not exe.exists():
        sys.exit(f"Besu {BESU_VERSION} not found at {exe}. See chain/README.md for the verified download.")
    return exe


def java_home() -> str:
    jdks = sorted(TOOLS.glob("jdk-25*"))
    if not jdks:
        sys.exit("Portable JDK 25 not found in chain/tools/. See chain/README.md.")
    return str(jdks[-1])


def besu_env() -> dict:
    env = dict(os.environ)
    env["JAVA_HOME"] = java_home()
    env["PATH"] = str(Path(env["JAVA_HOME"]) / "bin") + os.pathsep + env.get("PATH", "")
    return env


def foundry(tool: str) -> str:
    found = shutil.which(tool) or shutil.which(str(Path.home() / ".foundry" / "bin" / tool))
    if not found:
        sys.exit(f"{tool} not found; install Foundry (see MEMORY.md).")
    return found


def rpc(port: int, method: str, params=None, timeout=3):
    body = json.dumps({"jsonrpc": "2.0", "id": 1, "method": method, "params": params or []}).encode()
    req = urllib.request.Request(f"http://{HOST}:{port}", body, {"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        out = json.loads(resp.read())
    if "error" in out:
        raise RuntimeError(out["error"])
    return out["result"]


def node_dir(i: int) -> Path:
    return GENERATED / "nodes" / f"node{i}"


def enode(i: int) -> str:
    pub = (node_dir(i) / "key.pub").read_text().strip().removeprefix("0x")
    return f"enode://{pub}@{HOST}:{P2P_BASE + i - 1}"


def pid_file(i: int) -> Path:
    return DATA / f"node{i}" / "besu.pid"


def parse_nodes(args) -> list:
    if not args:
        return list(range(1, NODES + 1))
    return [int(a.removeprefix("node")) for a in args]


# ------------------------------------------------------------------ setup


def create_accounts():
    if ACCOUNTS_FILE.exists():
        print(f"Dev accounts already exist: {ACCOUNTS_FILE.relative_to(CHAIN.parent)}")
        return
    out = subprocess.run(
        [foundry("cast"), "wallet", "new", "--number", str(len(ROLES)), "--json"],
        check=True, capture_output=True, text=True,
    ).stdout
    parsed = json.loads(out)
    # Newer Foundry wraps results in {"schema_version", "success", "data": [...]}.
    wallets = parsed["data"] if isinstance(parsed, dict) else parsed
    lines = [
        "# LOCAL DEV ONLY. Generated by chain/net.py for the local Besu network. Never commit, never reuse.",
        f"CHAIN_ID={CHAIN_ID}",
        f"RPC_URL=http://{HOST}:{RPC_BASE}",
    ]
    for role, w in zip(ROLES, wallets):
        lines.append(f"{role}={w['address']}")
        lines.append(f"{role}_KEY={w['private_key']}")
    ACCOUNTS_FILE.write_text("\n".join(lines) + "\n")
    print(f"Created {len(ROLES)} dev accounts in {ACCOUNTS_FILE.relative_to(CHAIN.parent)} (git-ignored).")


def load_accounts() -> dict:
    env = {}
    for line in ACCOUNTS_FILE.read_text().splitlines():
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            env[k] = v
    return env


def generate_network(force: bool):
    if (GENERATED / "genesis.json").exists() and not force:
        print("Network already generated (use setup --force to regenerate keys and genesis).")
        return
    if GENERATED.exists():
        shutil.rmtree(GENERATED)
    GENERATED.mkdir(parents=True)
    accounts = load_accounts()

    config = {
        "genesis": {
            "config": {
                "chainId": CHAIN_ID,
                "berlinBlock": 0,
                "londonBlock": 0,
                "shanghaiTime": 0,
                "cancunTime": 0,
                "zeroBaseFee": True,
                "qbft": {"blockperiodseconds": 2, "epochlength": 30000, "requesttimeoutseconds": 4},
            },
            "nonce": "0x0",
            "timestamp": "0x0",
            "gasLimit": "0x1fffffffffffff",
            "difficulty": "0x1",
            "mixHash": "0x63746963616c2062797a616e74696e65206661756c7420746f6c6572616e6365",
            "coinbase": "0x0000000000000000000000000000000000000000",
            # The native coin has no value here (gas price is zero); balances only keep tooling happy.
            "alloc": {accounts[r].lower().removeprefix("0x"): {"balance": "0x3635C9ADC5DEA00000"} for r in ROLES},
        },
        "blockchain": {"nodes": {"generate": True, "count": NODES}},
    }
    cfg_path = GENERATED / "qbftConfigFile.json"
    cfg_path.write_text(json.dumps(config, indent=2))
    files = GENERATED / "networkFiles"
    subprocess.run(
        [str(besu_bin()), "operator", "generate-blockchain-config",
         f"--config-file={cfg_path}", f"--to={files}", "--private-key-file-name=key"],
        check=True, env=besu_env(), capture_output=True, text=True,
    )
    shutil.copy(files / "genesis.json", GENERATED / "genesis.json")

    key_dirs = sorted((files / "keys").iterdir())
    for i, kd in enumerate(key_dirs, start=1):
        nd = node_dir(i)
        nd.mkdir(parents=True)
        shutil.copy(kd / "key", nd / "key")
        shutil.copy(kd / "key.pub", nd / "key.pub")
        (nd / "address").write_text(kd.name)

    enodes = [enode(i) for i in range(1, NODES + 1)]
    (GENERATED / "permissions_config.toml").write_text(
        "# Only these nodes may connect (node allow-list).\nnodes-allowlist=[\n"
        + ",\n".join(f'  "{e}"' for e in enodes) + "\n]\n"
    )
    # Static peering with discovery off: nodes only ever dial the known validators.
    (GENERATED / "static-nodes.json").write_text(json.dumps(enodes, indent=2))
    for i in range(1, NODES + 1):
        nd = node_dir(i)
        toml = f"""# Validator node{i} (generated by chain/net.py)
data-path="{(DATA / f'node{i}').as_posix()}"
genesis-file="{(GENERATED / 'genesis.json').as_posix()}"
node-private-key-file="{(nd / 'key').as_posix()}"
p2p-host="{HOST}"
p2p-interface="{HOST}"
p2p-port={P2P_BASE + i - 1}
discovery-enabled=false
static-nodes-file="{(GENERATED / 'static-nodes.json').as_posix()}"
permissions-nodes-config-file-enabled=true
permissions-nodes-config-file="{(GENERATED / 'permissions_config.toml').as_posix()}"
rpc-http-enabled=true
rpc-http-host="{HOST}"
rpc-http-port={RPC_BASE + i - 1}
rpc-http-api=["{'","'.join(RPC_APIS.split(','))}"]
host-allowlist=["localhost","{HOST}"]
min-gas-price=0
metrics-enabled=false
logging="INFO"
"""
        (nd / "config.toml").write_text(toml)
    print(f"Generated genesis (chain ID {CHAIN_ID}), {NODES} validator keys and node configs in chain/network/generated/.")


def cmd_setup(args):
    NETWORK.mkdir(exist_ok=True)
    create_accounts()
    generate_network(force="--force" in args)


# ------------------------------------------------------------------ run


def is_running(i: int) -> bool:
    try:
        rpc(RPC_BASE + i - 1, "net_version", timeout=1)
        return True
    except Exception:
        return False


def upgrade_node_configs():
    """Adds settings introduced after a network was generated (keys and genesis stay as they are)."""
    for i in range(1, NODES + 1):
        cfg = node_dir(i) / "config.toml"
        text = cfg.read_text()
        # P2P listens on localhost only; before this line Besu bound P2P to all interfaces.
        if "p2p-interface=" not in text:
            cfg.write_text(text.replace(f'p2p-host="{HOST}"\n', f'p2p-host="{HOST}"\np2p-interface="{HOST}"\n', 1))
            print(f"node{i}: config upgraded (p2p-interface={HOST}); restart the node to apply")


def cmd_start(args):
    if not (GENERATED / "genesis.json").exists():
        sys.exit("Run `python chain/net.py setup` first.")
    upgrade_node_configs()
    for i in parse_nodes(args):
        if is_running(i):
            print(f"node{i} already running")
            continue
        (DATA / f"node{i}").mkdir(parents=True, exist_ok=True)
        log = open(DATA / f"node{i}" / "besu.log", "ab")
        flags = subprocess.CREATE_NEW_PROCESS_GROUP if os.name == "nt" else 0
        proc = subprocess.Popen(
            [str(besu_bin()), f"--config-file={node_dir(i) / 'config.toml'}"],
            env=besu_env(), stdout=log, stderr=subprocess.STDOUT, creationflags=flags,
        )
        pid_file(i).write_text(str(proc.pid))
        print(f"node{i} starting (pid {proc.pid}, rpc {HOST}:{RPC_BASE + i - 1}, log chain/data/node{i}/besu.log)")
    wait_for_blocks()


def wait_for_blocks(timeout=120):
    deadline = time.time() + timeout
    first = None
    while time.time() < deadline:
        try:
            n = int(rpc(RPC_BASE, "eth_blockNumber"), 16)
            if first is None:
                first = n
            elif n > first:
                print(f"Producing blocks: height {n}")
                return
        except Exception:
            pass
        time.sleep(2)
    print("Warning: no new blocks yet; check chain/data/node*/besu.log")


def cmd_stop(args):
    for i in parse_nodes(args):
        pf = pid_file(i)
        if not pf.exists():
            continue
        pid = int(pf.read_text())
        if os.name == "nt":
            subprocess.run(["taskkill", "/PID", str(pid), "/T", "/F"], capture_output=True)
        else:
            try:
                os.kill(pid, signal.SIGTERM)
            except ProcessLookupError:
                pass
        pf.unlink()
        print(f"node{i} stopped")


def cmd_status(_args):
    for i in range(1, NODES + 1):
        port = RPC_BASE + i - 1
        try:
            height = int(rpc(port, "eth_blockNumber"), 16)
            peers = int(rpc(port, "net_peerCount"), 16)
            validators = rpc(port, "qbft_getValidatorsByBlockNumber", ["latest"])
            print(f"node{i}: height {height}, peers {peers}, validators {len(validators)}")
        except Exception:
            print(f"node{i}: not reachable")


def cmd_reset(_args):
    cmd_stop([])
    if DATA.exists():
        shutil.rmtree(DATA)
    print("Chain data deleted (keys, genesis and accounts kept).")


COMMANDS = {"setup": cmd_setup, "start": cmd_start, "stop": cmd_stop, "status": cmd_status, "reset": cmd_reset}

if __name__ == "__main__":
    if len(sys.argv) < 2 or sys.argv[1] not in COMMANDS:
        sys.exit(__doc__)
    COMMANDS[sys.argv[1]](sys.argv[2:])
